"""VGG19 inference service: input verification, prediction and Grad-CAM."""

from __future__ import annotations

import json
import threading
import time
from pathlib import Path

import numpy as np
import torch
from PIL import Image

from app.config import Settings
from app.core.architecture import (
    IMAGENET_MEAN,
    IMAGENET_STD,
    VGG19Classifier,
    build_model,
    load_checkpoint,
)
from app.core.gradcam import GradCAM, overlay_heatmap
from app.core.input_quality import analyse_crop, crop_to_tensor, model_crop
from app.services.input_gate import InputGate, InputRejectedError

DISCLAIMER = (
    "This result is generated by an artificial intelligence model for academic "
    "demonstration only. It is not a medical diagnosis and must not replace "
    "examination or advice from a qualified pathologist or physician."
)


class ModelNotReadyError(RuntimeError):
    """Raised when predictions are requested before a checkpoint is available."""


class ModelService:
    """Thread-safe wrapper around the trained VGG19 classifier."""

    def __init__(self, settings: Settings) -> None:
        self.settings = settings
        self.device = torch.device("cpu")
        self.model: VGG19Classifier | None = None
        self.metadata: dict = {}
        self.metrics: dict = {}
        self.error: str | None = None
        self.gate = InputGate(settings.reference_stats_path, enabled=settings.input_validation)
        self._lock = threading.Lock()

    # ------------------------------------------------------------------ setup
    def load(self) -> None:
        torch.set_num_threads(max(1, self.settings.torch_threads))
        self.gate.load()
        try:
            model = build_model(pretrained=True, torch_home=self.settings.torch_home)
            blob = load_checkpoint(model, self.settings.model_path)
            model.to(self.device).eval()
            self.model = model
            self.metadata = {
                key: value for key, value in blob.items() if key not in {"state_dict", "classifier", "metrics"}
            }
            self.metrics = blob.get("metrics", {})
            self.error = None
        except Exception as exc:  # noqa: BLE001 - surfaced through /health
            self.model = None
            self.error = f"{type(exc).__name__}: {exc}"

    @property
    def ready(self) -> bool:
        return self.model is not None

    @property
    def threshold(self) -> float:
        return float(self.metadata.get("threshold", 0.5))

    @property
    def parameters(self) -> int:
        return sum(p.numel() for p in self.model.parameters()) if self.model else 0

    # -------------------------------------------------------------- inference
    def predict(self, image: Image.Image, want_grad_cam: bool = True) -> dict:
        """Verify the image, then classify it and optionally generate Grad-CAM.

        Raises :class:`InputRejectedError` when the upload is outside the
        histopathology input domain; no prediction is produced in that case.
        """
        if self.model is None:
            raise ModelNotReadyError(self.error or "Model checkpoint not loaded")

        started = time.perf_counter()
        # One crop is shared by the domain check, the classifier and Grad-CAM so
        # the explanation always refers to exactly the pixels that were scored.
        crop = model_crop(image)
        metrics = analyse_crop(crop, original_size=image.size)
        tensor = crop_to_tensor(crop, IMAGENET_MEAN, IMAGENET_STD).unsqueeze(0).to(self.device)
        threshold = self.threshold

        with self._lock:
            with torch.no_grad():
                features = self.model.embed(tensor)
                verdict = self.gate.evaluate(metrics, features[0].cpu().numpy())
                if not verdict.accepted:
                    raise InputRejectedError(verdict)
                logits = self.model.classify(features)
                probabilities = torch.softmax(logits, dim=1)[0].numpy()

            malignant_probability = float(probabilities[1])
            # The decision must follow the validation-selected threshold, not the
            # raw argmax: with threshold < 0.5 those two can disagree.
            predicted_index = 1 if malignant_probability >= threshold else 0
            heatmap = None
            if want_grad_cam:
                with GradCAM(self.model) as explainer:
                    heatmap = explainer.generate(tensor, class_index=predicted_index)

        overlay = None
        if heatmap is not None:
            overlay = overlay_heatmap(np.asarray(crop), heatmap)

        return {
            "probabilities": {
                "benign": float(probabilities[0]),
                "malignant": malignant_probability,
            },
            "predicted_index": predicted_index,
            "predicted_label": "malignant" if predicted_index == 1 else "benign",
            "probability": float(probabilities[predicted_index]),
            "threshold": threshold,
            "risk_level": self._risk_level(malignant_probability, threshold),
            "heatmap": heatmap,
            "overlay": overlay,
            "latency_ms": int((time.perf_counter() - started) * 1000),
            "input_check": verdict.details,
        }

    @staticmethod
    def _risk_level(malignant_probability: float, threshold: float) -> str:
        if malignant_probability >= 0.70:
            return "high"
        if malignant_probability >= threshold:
            return "moderate"
        return "low"

    # ------------------------------------------------------------------- info
    def validation_status(self) -> dict:
        return self.gate.status()

    def load_metrics_file(self) -> dict:
        path: Path = self.settings.metrics_path
        if path.is_file():
            try:
                return json.loads(path.read_text(encoding="utf-8"))
            except json.JSONDecodeError:
                return {}
        return {}
